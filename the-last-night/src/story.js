export function objectiveText(s) {
  const f = s.flags;
  const inv = s.inv;
  if (!inv.flashlight) return 'Finde eine Lichtquelle.';
  if (f.override) return 'LAUF! Der Haupteingang in der Eingangshalle ist offen.';
  if (f.power) {
    if (f.shelfOpen) return 'Betätige die manuelle Freigabe im Privatarchiv.';
    return 'Löse die Notverriegelung – Büro des Direktors (Personaltrakt).';
  }
  if (inv.basementKey || f.orOpen) {
    const total = inv.fuses + (f.fusesInserted || 0);
    if (f.fusesInserted >= 3) return 'Ziehe den Hebel am Generator im Keller.';
    if (!inv.basementKey) return 'Durchsuche den Operationssaal.';
    return `Bringe Sicherungen zum Generator im Keller (${total}/3).`;
  }
  if (f.codeKnown) return `Öffne den OP im Nordflügel mit dem Code ${s.code}.`;
  if (inv.staffKey) return 'Finde den Code für den OP – Überwachungsraum im Personaltrakt.';
  if (f.readShift) return 'Hole den Personalschlüssel aus der Hydrotherapie (Nordflügel, über Isolation 1).';
  if (f.seenExit) return 'Der Ausgang ist verriegelt. Durchsuche die Schwesternstation.';
  return 'Verlasse dein Zimmer und finde einen Weg nach draußen.';
}
